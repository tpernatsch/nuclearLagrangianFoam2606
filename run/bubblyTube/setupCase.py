P_ATM = 101325.0
R_UNIVERSAL = 8314.46
T_STD_OF = 298.15            # OpenFOAM Tstd for hConst / eConst sensible energy

FLUIDS = {
    # [dW] Table 3.2 (AG40 at 293 K) and standard water data at 293 K
    "AG40":  dict(rho=1100.0, mu=3.63e-3, sigma=0.070, Cp=3350.0, W=26.6, Pr=25.33),
    "water": dict(rho=998.2, mu=1.002e-3, sigma=0.0728, Cp=4182.0, W=18.02, Pr=7.0),
}
AIR = dict(W=28.9, Cp=1007.0, mu=1.84e-5, Pr=0.7)          # [dW] Table 3.2

MESH_LEVELS = {                                          # [dW] Table C.1 cell sizes
    "coarse":    dict(Nc=8,  Nr=4, dz=0.003),
    "medium":    dict(Nc=12, Nr=4, dz=0.002),
    "fine":      dict(Nc=16, Nr=6, dz=0.0015),
    "extrafine": dict(Nc=22, Nr=8, dz=0.3 / 260),
}
