class Ask:
    """Small input helpers: every question shows its suggested answer, Enter accepts it."""

    @staticmethod
    def _read(prompt):
        try:
            return input(prompt).strip()
        except EOFError:
            print()
            return ""

    @staticmethod
    def choice(question, options, default, notes=None):
        """options: list of (value, description). Returns the chosen value."""
        print(f"\n{question}")
        keys = [o[0] for o in options]
        for i, (val, desc) in enumerate(options, 1):
            mark = "  <- suggested" if val == default else ""
            print(f"   {i}) {desc}{mark}")
        if notes:
            print(f"   ({notes})")
        dflt = keys.index(default) + 1
        while True:
            a = Ask._read(f"   choose 1-{len(options)} [{dflt}]: ")
            if not a:
                return default
            if a.isdigit() and 1 <= int(a) <= len(options):
                return keys[int(a) - 1]
            print(f"   ! please type a number between 1 and {len(options)}")

    @staticmethod
    def number(question, default, lo, hi, unit="", pattern=None, pattern_hint=None, soft=None):
        """Float in [lo, hi]. pattern: regex the text must match. soft=(a, b): outside -> confirm."""
        print(f"\n{question}")
        while True:
            a = Ask._read(f"   value{(' [' + unit + ']') if unit else ''} [{default}]: ") or str(default)
            if pattern and not re.fullmatch(pattern, a):
                print(f"   ! format must be {pattern_hint}")
                continue
            try:
                v = float(a)
            except ValueError:
                print("   ! not a number")
                continue
            if not lo <= v <= hi:
                print(f"   ! must be between {lo:g} and {hi:g} {unit}")
                continue
            if soft and not soft[0] <= v <= soft[1]:
                if not Ask.yes(f"   {v} {unit} is outside the suggested range {soft[0]}-{soft[1]} {unit}. Use it anyway?", False):
                    continue
            return v

    @staticmethod
    def numbers(question, default, lo, hi, unit="", pattern=None, pattern_hint=None, soft=None):
        """Comma-separated list of floats."""
        print(f"\n{question}")
        dtxt = ", ".join(f"{x:g}" for x in default)
        while True:
            a = Ask._read(f"   values{(' [' + unit + ']') if unit else ''} [{dtxt}]: ") or dtxt
            items = [x.strip() for x in a.replace(";", ",").split(",") if x.strip()]
            bad = [x for x in items if pattern and not re.fullmatch(pattern, x)]
            if bad:
                print(f"   ! {', '.join(bad)}: format must be {pattern_hint}")
                continue
            try:
                vals = [float(x) for x in items]
            except ValueError:
                print("   ! not a list of numbers")
                continue
            out = [v for v in vals if not lo <= v <= hi]
            if out or not vals:
                print(f"   ! every value must be between {lo:g} and {hi:g} {unit}")
                continue
            if soft and any(not soft[0] <= v <= soft[1] for v in vals):
                if not Ask.yes(f"   some values are outside the suggested range {soft[0]}-{soft[1]} {unit}. Use them anyway?", False):
                    continue
            return sorted(set(vals))

    @staticmethod
    def yes(question, default):
        while True:
            a = Ask._read(f"{question} [{'Y/n' if default else 'y/N'}]: ").lower()
            if not a:
                return default
            if a in ("y", "yes"):
                return True
            if a in ("n", "no"):
                return False


