# ============================================================================= main
def main():
    argv = sys.argv[1:]
    force = "--force" in argv
    if "--from" in argv:
        src = os.path.abspath(argv[argv.index("--from") + 1])
        cfg, interactive, note = load_config(src), False, f"replayed from {src}"
    else:
        cfg = load_config(os.path.join(HERE, "caseDefaults.py"))
        interactive = "--defaults" not in argv
        note = "questionnaire" if interactive else "caseDefaults.py"
    if not isinstance(cfg.Q_LPM, (list, tuple)):
        cfg.Q_LPM = [cfg.Q_LPM]

    if interactive:
        questionnaire(cfg)
        print_overview(cfg)
        if not Ask.yes("\nCreate the case(s)?", True):
            raise SystemExit("nothing written")

    if cfg.LIQUID not in FLUIDS:
        raise SystemExit(f"LIQUID must be one of {list(FLUIDS)}")
    if not cfg.MESH_CUSTOM and cfg.MESH_LEVEL not in MESH_LEVELS:
        raise SystemExit(f"MESH_LEVEL must be one of {list(MESH_LEVELS)}")
    base = cfg.OUTPUT_DIR if os.path.isabs(cfg.OUTPUT_DIR) else os.path.join(HERE, cfg.OUTPUT_DIR)

    for Q in cfg.Q_LPM:
        d = derive(cfg, Q)
        name = cfg.CASE_NAME.format(Q=f"{Q:g}", db=f"{1e3*d['db']:.3g}mm",
                                    turb=TURB_TAGS.get(cfg.TURBULENCE, cfg.TURBULENCE),
                                    mesh=cfg.MESH_LEVEL if not cfg.MESH_CUSTOM else "custom")
        root = os.path.join(base, name)
        if os.path.exists(root):
            if not (force or (interactive and Ask.yes(f"\n{root} exists. Overwrite?", False))):
                print(f"[skip] {root}")
                continue
            shutil.rmtree(root)
        os.makedirs(root)
        c = Case(root)
        warnings = checks(cfg, d)
        write_mesh(c, cfg, d)
        write_fields(c, cfg, d)
        write_constant(c, cfg, d)
        write_system(c, cfg, d)
        write_scripts(c, cfg, d)
        one = types.SimpleNamespace(**vars(cfg))
        one.Q_LPM = [Q]
        save_config(one, os.path.join(root, "caseSettings.py"), note)
        lines = write_summary(c, cfg, d, warnings, note)
        print(f"\n=== {root}")
        print("\n".join(lines))


if __name__ == "__main__":
    main()
