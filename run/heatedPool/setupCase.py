# ============================================================================= initial fields from a finished case
def latest_time(case):
    """Name of the latest written time > 0 of a finished (reconstructed) case."""
    times = []
    for n in os.listdir(case):
        try:
            t = float(n)
        except ValueError:
            continue
        if t > 0 and os.path.isdir(os.path.join(case, n)):
            times.append((t, n))
    if not times:
        if os.path.isdir(os.path.join(case, "processor0")):
            raise SystemExit(f"INITIAL_FIELDS: {case} has only decomposed results: "
                             "run 'reconstructPar -latestTime' there first")
        raise SystemExit(f"INITIAL_FIELDS: {case} has no written time > 0")
    return max(times)[1]


def internal_field_span(txt, path):
    """Start/end of the 'internalField ...;' entry (uniform or nonuniform list) of an ascii field file."""
    m = re.search(r"^internalField\s", txt, flags=re.M)
    b = re.search(r"^boundaryField\s", txt, flags=re.M)
    if not m or not b:
        raise SystemExit(f"INITIAL_FIELDS: no internalField/boundaryField in {path}")
    return m.start(), txt.rfind(";", m.start(), b.start()) + 1


STATE_KEYS = ("value", "refValue", "refGradient", "valueFraction", "gradient")


def patch_entry(txt, patch, key):
    """Value of entry 'key' of boundaryField/patch in a written field file (uniform or list), or None."""
    b = re.search(r"^boundaryField\s", txt, flags=re.M)
    if not b or not patch:
        return None
    m = re.search(rf"^    {re.escape(patch)}\s*\n    \{{", txt[b.start():], flags=re.M)
    if not m:
        return None
    start = b.start() + m.end()
    end = re.search(r"^    \}", txt[start:], flags=re.M)
    block = txt[start:start + end.start()] if end else txt[start:]
    e = re.search(rf"^\s+{re.escape(key)}\s+(.*?);", block, flags=re.M | re.S)
    return e.group(1).strip() if e else None


def apply_initial_fields(root, src):
    """Put the internal fields of the latest time of the finished case src into root/0.orig.
    The boundary conditions stay those of the new case; the mesh must be identical (same blockMeshDict).
    Returns (time, [fields])."""
    if not os.path.isdir(src):
        raise SystemExit(f"INITIAL_FIELDS: {src} not found")
    def foam_body(txt):     # without the banner and FoamFile header
        return txt[txt.index("}", txt.index("FoamFile")) + 1:] if "FoamFile" in txt else txt

    body = [foam_body(open(os.path.join(r, "system", "blockMeshDict")).read()) for r in (src, root)]
    if body[0] != body[1]:
        raise SystemExit(f"INITIAL_FIELDS: the mesh of {src} differs from this case's (blockMeshDict): "
                         "same geometry, MESH_LEVEL, BOUNDARY_LAYER and MESH_TYPE needed (or use mapFields)")
    t = latest_time(src)
    orig, done = os.path.join(root, "0.orig"), []
    for dirpath, _, files in os.walk(orig):
        rel = os.path.relpath(dirpath, orig)
        for f in sorted(files):
            sp = os.path.normpath(os.path.join(src, t, rel, f))
            if not os.path.isfile(sp):
                continue
            stxt = open(sp).read()
            if re.search(r"^\s*format\s+binary", stxt, flags=re.M):
                raise SystemExit(f"INITIAL_FIELDS: {sp} is binary (writeFormat ascii needed)")
            tp = os.path.join(dirpath, f)
            ttxt = open(tp).read()
            s0, s1 = internal_field_span(stxt, sp)
            t0, t1 = internal_field_span(ttxt, tp)
            # Patch state (value, refValue, refGradient, valueFraction, gradient) from the finished case
            # when the patch type is the same: the generated placeholders would start the first step from
            # wrong wall values (a mixed BC is evaluated from refValue/refGradient/valueFraction when read,
            # fixedFluxPressure needs its gradient for the hydrostatic balance), which kicks the momentum
            # predictor. A '$internalField' left (no source entry) gets the generated uniform value,
            # since the macro cannot expand a nonuniform list.
            uni = ttxt[t0:t1 - 1].split(None, 1)[1].strip()
            out, patch, keys, same = [], None, set(), False
            for line in ttxt[t1:].splitlines(keepends=True):
                m = re.match(r"^    ([^\s{}]+)\s*$", line)
                if m:
                    patch, keys, same = m.group(1), set(), False
                tok = line.split()
                if tok:
                    keys.add(tok[0])
                if len(tok) > 1 and tok[0] == "type":
                    same = patch_entry(stxt, patch, "type") == tok[1].rstrip(";")
                if same and tok and tok[0] in STATE_KEYS and line.rstrip().endswith(";"):
                    src_val = patch_entry(stxt, patch, tok[0])
                    if src_val is not None:
                        line = f"{line[:len(line) - len(line.lstrip())]}{tok[0]:<16}{src_val};\n"
                    grad = patch_entry(stxt, patch, "gradient")
                    if tok[0] == "value" and grad is not None and "gradient" not in keys:
                        out.append(f"        gradient        {grad};\n")     # fixedFluxPressure
                out.append(line.replace("$internalField", uni))
            with open(tp, "w") as fh:
                fh.write(ttxt[:t0] + stxt[s0:s1] + "".join(out))
            done.append(os.path.normpath(os.path.join(rel, f)))
    if not done:
        raise SystemExit(f"INITIAL_FIELDS: no field of 0.orig found in {src}/{t}")
    # derived fields copied whole (computed values only): the conservative face flux avoids a pressure
    # jolt at the first step (an interpolated phi gives initial U residuals ~1 instead of ~1e-5)
    for f in ("phi", "p"):
        sp = os.path.join(src, t, f)
        if os.path.isfile(sp) and not os.path.exists(os.path.join(orig, f)):
            shutil.copy(sp, os.path.join(orig, f))
            done.append(f)
    return t, done


