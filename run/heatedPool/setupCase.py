def write_constant(c, cfg, d):
    c.write("constant/g", """
dimensions      [0 1 -2 0 0 0 0];
value           (0 0 -9.81);
""", cls="uniformDimensionedVectorField", obj="g")
    if cfg.VISCOSITY["model"] == "arrhenius":
        vis = cfg.VISCOSITY
        visc = f"""
// mu(T) = {vis['mu0']:g} Pa s * exp({vis['Ea']:g}/(R T)), as nu = nu(TRef) exp(-alpha (T - TRef)):
// the tangent of the Arrhenius law at TRef in log space (within ~1 % over +-60 K).
// The T equation keeps k constant through the fvOption 'constantConductivity'.
transportModel  ArrheniusNewtonian;

nu              {fmt(d['nu'])};      // mu(TRef)/rho [m2/s]
alpha           {d['alpha_mu']:.6g};      // Ea/(R TRef^2) [1/K]
Talpha          {fmt(cfg.T_REF)};
field           T;
"""
    else:
        visc = f"""
transportModel  Newtonian;

nu              {fmt(d['nu'])};      // mu/rho [m2/s]
"""
    c.write("constant/transportProperties", f"""
// Liquid: rho = {cfg.RHO} kg/m3, cp = {cfg.CP} J/kg/K, k = {cfg.K} W/m/K, mu(TRef) = {d['mu']:.4g} Pa s
{visc.strip()}

beta            {fmt(cfg.BETA)};      // [1/K]
TRef            {fmt(cfg.T_REF)};    // [K]
Pr              {fmt(d['Pr'])};      // mu cp/k
Prt             {PRT};

rhoRef          {fmt(cfg.RHO)};      // radiation source: divided by rhoRef*CpRef
CpRef           {fmt(cfg.CP)};
""")
    c.write("constant/turbulenceProperties", """
simulationType  laminar;
""")
    if radiation_on(cfg):
        write_radiation(c, cfg, d)
    if density_coupled(cfg):
        Pm = cfg.SALT_POWER * 1e3                    # W/kg
        src = f"""
// Salt heat generation {cfg.SALT_POWER:g} W/g x rho(T): q''' = P_m rho0 (1 - beta (T - TRef)), so the Boussinesq
// T source is P_m/cp (1 - beta (T - TRef)) = Su + Sp T (per volume, K/s): hotter salt generates slightly less.
// At TRef: {fmt(q_vol(cfg))} W/m3, {fmt(d['Qgen'])} W in total.
heatSource
{{
    type            scalarSemiImplicitSource;
    selectionMode   all;
    volumeMode      specific;

    sources
    {{
        T
        {{
            explicit    constant {Pm / cfg.CP * (1 + cfg.BETA * cfg.T_REF):.12g};    // K/s
            implicit    constant {-Pm / cfg.CP * cfg.BETA:.12g};    // 1/s
        }}
    }}
}}"""
    else:
        src = f"""
// Uniform volumetric heat generation q''' = {fmt(q_vol(cfg))} W/m3 x nominal volume {d['V']:.6g} m3
// = {fmt(d['Qgen'])} W, given as a total (absolute) so it balances power-mode walls exactly.
// The Boussinesq T equation is kinematic: source = P/(rho cp) in K m3/s, spread over the volume.
heatSource
{{
    type            scalarSemiImplicitSource;
    selectionMode   all;
    volumeMode      absolute;

    sources
    {{
        T
        {{
            explicit    constant {d['Qgen'] * wedge_frac(cfg) / (cfg.RHO * cfg.CP):.12g};    // K m3/s  (= {fmt(d['ST'])} K/s)
            implicit    0;
        }}
    }}
}}"""
    fvo = f"""{src}
{level_pin(cfg, d) if d["all_flux"] else ""}
{CONST_K.replace("@A0@", f"{d['a']:.8g}").replace("@AMU@", f"{d.get('alpha_mu', 0):.8g}").replace("@TREF@", fmt(cfg.T_REF))
 if cfg.VISCOSITY["model"] == "arrhenius" else ""}"""
    if not particles_on(cfg):
        c.write("constant/fvOptions", fvo)
        return
    write_cloud(c, cfg, d)
    if len(stages(cfg)) == 1:
        c.write("constant/fvOptions", fvo + cloud_fvoption(cfg, d))
    else:       # the cloud only on the transient stage: Allrun swaps the files with the system ones
        c.write("constant/fvOptions.steady", fvo, obj="fvOptions")
        c.write("constant/fvOptions.transient", fvo + cloud_fvoption(cfg, d), obj="fvOptions")
        c.write("constant/fvOptions", fvo)


