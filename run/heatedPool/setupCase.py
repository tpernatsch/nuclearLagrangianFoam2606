# ============================================================================= questionnaire
class Ask:
    """Small input helpers: every question shows its suggested answer, Enter accepts it."""

    @staticmethod
    def _read(prompt):
        try:
            return input(prompt).strip()
        except EOFError:
            print()
            return ""

    @staticmethod
    def choice(question, options, default, notes=None):
        """options: list of (value, description). Returns the chosen value."""
        print(f"\n{question}")
        keys = [o[0] for o in options]
        for i, (val, desc) in enumerate(options, 1):
            mark = "  <- suggested" if val == default else ""
            print(f"   {i}) {desc}{mark}")
        if notes:
            print(f"   ({notes})")
        dflt = keys.index(default) + 1
        while True:
            a = Ask._read(f"   choose 1-{len(options)} [{dflt}]: ")
            if not a:
                return default
            if a.isdigit() and 1 <= int(a) <= len(options):
                return keys[int(a) - 1]
            print(f"   ! please type a number between 1 and {len(options)}")

    @staticmethod
    def number(question, default, lo, hi, unit="", soft=None):
        """Float in [lo, hi]. soft=(a, b): outside -> confirm."""
        print(f"\n{question}")
        while True:
            a = Ask._read(f"   value{(' [' + unit + ']') if unit else ''} [{default:g}]: ") or str(default)
            try:
                v = float(a)
            except ValueError:
                print("   ! not a number")
                continue
            if not lo <= v <= hi:
                print(f"   ! must be between {lo:g} and {hi:g} {unit}")
                continue
            if soft and not soft[0] <= v <= soft[1]:
                if not Ask.yes(f"   {v:g} {unit} is outside the suggested range {soft[0]:g}-{soft[1]:g} {unit}. Use it anyway?", False):
                    continue
            return v

    @staticmethod
    def yes(question, default):
        while True:
            a = Ask._read(f"{question} [{'Y/n' if default else 'y/N'}]: ").lower()
            if not a:
                return default
            if a in ("y", "yes"):
                return True
            if a in ("n", "no"):
                return False


def section(i, n, title):
    print(f"\n{'=' * 78}\n [{i}/{n}] {title}\n{'=' * 78}")


def ask_gas_h(cfg, old, spec, allow_auto, share=None):
    """Gas side: Ta, emissivity and h (calibrated 'auto', a value, or shared with another patch)."""
    opts = []
    if share:
        opts.append((share, f"same gas as {share} (its h and Ta)"))
    if allow_auto:
        opts.append(("auto", "unknown: calibrate h so the energy balance gives a measured temperature"))
    opts.append(("value", "known: type it in"))
    h0 = old.get("h", opts[0][0])
    how = Ask.choice("   gas-side heat transfer coefficient h?", opts,
                     h0 if h0 in [o[0] for o in opts] else "value")
    if how == share:
        spec["h"] = share
        spec["emissivity"] = Ask.number("   emissivity of the outer surface (0 = no radiation)",
                                        old.get("emissivity", cfg.CLADDING["emissivity"]), 0, 1)
        return
    spec["Ta"] = Ask.number("   gas / surroundings temperature Ta", old.get("Ta", 573.15), 200, 3000, "K")
    spec["emissivity"] = Ask.number("   emissivity of the outer surface (0 = no radiation)",
                                    old.get("emissivity", cfg.CLADDING["emissivity"]), 0, 1)
    if how == "auto":
        spec["h"] = "auto"
        targets = [("liquid", "in the liquid (mean of the thermocouples)")]
        if cfg.GEOMETRY == "A":
            targets.append(("innerWall", "on the axis inside the inner cladding ring (= inner-wall T + ring offset)"))
        targets += [("wall", "on the cladding, liquid side"),
                    ("surface", "on the cladding outer surface (gas side)")]
        t0 = old.get("target", "liquid")
        spec["target"] = Ask.choice("   where is the measured temperature?", targets,
                                    t0 if t0 in [t for t, _ in targets] else "liquid")
        spec["T_target"] = Ask.number("   measured (mean) temperature", old.get("T_target", 946.15), 250, 3000, "K")
        if spec["target"] in ("liquid", "innerWall"):
            col = "Tavg" if spec["target"] == "liquid" else "T_innerWall"
            spec["dT_internal"] = Ask.number(
                f"   {col} - Tw_loss (0 on the first run; then read it from\n"
                "   postProcessing/heatBalance_*.dat and regenerate)", old.get("dT_internal", 0.0), -500, 500, "K")
    else:
        h0 = old.get("h", 300.0)
        spec["h"] = Ask.number("   heat transfer coefficient h", 300.0 if isinstance(h0, str) else h0, 0, 1e6,
                               "W/m2/K", soft=(1, 1e4))


def ask_thermal(cfg, patch, label, allowed, allow_auto=False, share=None):
    old = dict(cfg.THERMAL_BC.get(patch, {"mode": "adiabatic"}))
    opts = [(k, v) for k, v in (
        ("split", "heat split by flux ratios (HEAT_SPLIT), side wall with the reference shape; level from LEVEL_PIN"),
        ("cladding", "Hastelloy cladding with heat generation (coded BC): conduction to a measured outer T, "
                     "or to the gas"),
        ("ring", "A inner ring: its own heat flows into the salt (or impose the axis thermocouples)"),
        ("coefficient", "layers + gas h + radiation (externalWallHeatFluxTemperature, no cladding generation)"),
        ("balance", "constant flux that removes all generated heat not lost elsewhere"),
        ("adiabatic", "adiabatic (zero gradient)"),
        ("relative", "heat flux = ratio x the mean heat flux through the outer wall (updated every iteration)"),
        ("flux", "fixed heat-loss flux q [W/m2]")) if k in allowed]
    mode = Ask.choice(f"{label}: thermal condition?", opts, old["mode"] if old["mode"] in allowed else allowed[0])
    spec = dict(mode=mode)
    if mode == "flux":
        spec["q_loss"] = Ask.number("   heat-loss flux, positive = heat leaving the liquid",
                                    old.get("q_loss", 1000.0), -1e7, 1e7, "W/m2")
    elif mode == "relative":
        spec["of"] = "outerWall"
        spec["ratio"] = Ask.number("   mean heat flux here / mean heat flux through the outer wall",
                                   old.get("ratio", 0.34 if patch == "bottom" else 0.17), 0, 100)
    elif mode == "ring":
        spec["impose_tc"] = Ask.yes("   impose the axis thermocouple profile on the inner wall (instead of using\n"
                                    "   the thermocouples to validate)?", old.get("impose_tc", False))
    elif mode == "cladding":
        has_tc = "outer" in (cfg.THERMOCOUPLES.get(cfg.GEOMETRY) or {}) and patch in ("outerWall", "bottom")
        outside = "gas"
        if has_tc:
            outside = Ask.choice("   outside of the cladding?", [
                ("measured", "thermocouple profile on the outer surface (THERMOCOUPLES)"),
                ("gas", "gas convection + radiation"),
            ], old.get("outside", "measured"))
        spec["outside"] = outside
        if outside == "gas":
            ask_gas_h(cfg, old, spec, allow_auto, share)
    elif mode == "coefficient":
        lay = old.get("layers")
        if lay == "cladding" or not lay:
            lay = cladding_layers(cfg, patch) if patch != "freeSurface" else [(1.0e-3, cfg.CLADDING["k"])]
        t = Ask.number("   cladding thickness (0 = no cladding)", 1e3 * lay[0][0], 0, 100, "mm")
        if t > 0:
            kc = Ask.number("   cladding thermal conductivity", lay[0][1], 1e-3, 1000, "W/m/K")
            spec["layers"] = [(1e-3 * t, kc)] + lay[1:]
        else:
            spec["layers"] = []
        ask_gas_h(cfg, old, spec, allow_auto, share)
    cfg.THERMAL_BC[patch] = spec


def mesh_rows(cfg):
    rows = []
    keep = cfg.MESH_LEVEL
