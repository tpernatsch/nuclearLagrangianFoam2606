def write_mesh_annulus(c, cfg, d):
    m = d["mesh"]
    ri, ro, H = cfg.A_INNER_DIAMETER / 2, cfg.A_OUTER_DIAMETER / 2, cfg.A_HEIGHT

    def pt(r, ang, z):
        return f"({fmt(r * math.cos(math.radians(ang)))} {fmt(r * math.sin(math.radians(ang)))} {fmt(z)})"

    verts = []
    for z in (0, H):
        for r in (ri, ro):
            verts.append(" ".join(pt(r, 90 * q, z) for q in range(4)))
    labels = ["0-3   inner, z = 0", "4-7   outer, z = 0", "8-11  inner, z = H", "12-15 outer, z = H"]
    vtxt = "\n".join(f"    {v}   // {l}" for v, l in zip(verts, labels))

