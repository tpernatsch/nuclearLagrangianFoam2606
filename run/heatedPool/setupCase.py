def load_config(path):
    """Load a settings file into a plain namespace of its UPPER_CASE names."""
    spec = importlib.util.spec_from_file_location("settings", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return types.SimpleNamespace(**{k: getattr(mod, k) for k in dir(mod) if k.isupper()})


def save_config(cfg, path, note):
    with open(path, "w") as f:
        f.write(f'"""Settings used to generate this case ({note}).\n'
                f'Regenerate with:  python3 setupCase.py --from {os.path.basename(path)}"""\n\n')
        for k in sorted(vars(cfg)):
            f.write(f"{k} = {getattr(cfg, k)!r}\n")


def fmt(x):
    return f"{x:.6g}"


def indent(text, n):
    pad = " " * n
    return "\n".join(pad + l if l.strip() else l for l in text.strip("\n").splitlines())


class Case:
    def __init__(self, root):
        self.root = root

    def write(self, rel, body, cls="dictionary", obj=None):
        path = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(HDR.format(cls=cls, obj=obj or os.path.basename(rel)))
            f.write(body.strip("\n") + "\n" + FTR)

    def write_raw(self, rel, text, executable=False):
        path = os.path.join(self.root, rel)
        with open(path, "w") as f:
            f.write(text)
        if executable:
            os.chmod(path, 0o755)


# ============================================================================= grading
def solve_ratio(L, n, d1):
    """Cell-to-cell ratio r such that n cells starting at d1 fill L (geometric series)."""
    if n * d1 >= L:
        return 1.0
    f = lambda r: d1 * (r ** n - 1) / (r - 1) - L
    lo, hi = 1.0 + 1e-12, 2.0
    while f(hi) < 0:
        hi *= 2
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if f(mid) < 0 else (lo, mid)
    return 0.5 * (lo + hi)


def graded(L, h, d1, rmax, start, end):
    """Cells along an edge of length L with uniform size h and optional geometric wall
    refinement (first cell d1, cell-to-cell ratio <= rmax) at its start and/or end.
    Returns (sections, N); a section is (length, cells, last/first expansion)."""
    n_u = max(1, math.ceil(L / h - 1e-9))
    sides = int(start) + int(end)
    if sides == 0 or d1 >= h:
        return [(L, n_u, 1.0)], n_u
    n_g = max(1, math.ceil(math.log(h / d1) / math.log(rmax)))
    Lg = d1 * (rmax ** n_g - 1) / (rmax - 1)
    if sides * Lg < 0.8 * L:                   # wall layer + uniform core
        grow = rmax ** (n_g - 1)
        Lc = L - sides * Lg
        secs = ([(Lg, n_g, grow)] if start else []) + [(Lc, max(1, math.ceil(Lc / h)), 1.0)] \
            + ([(Lg, n_g, 1 / grow)] if end else [])
    else:                                      # the wall layer(s) fill the whole edge
        Ls = L / sides
        n = max(2, math.ceil(Ls / h))
        while solve_ratio(Ls, n, d1) > rmax:
            n += 1
        grow = solve_ratio(Ls, n, d1) ** (n - 1)
        secs = ([(Ls, n, grow)] if start else []) + ([(Ls, n, 1 / grow)] if end else [])
    return secs, sum(s[1] for s in secs)


def cell_sizes(secs):
    out = []
    for l, n, e in secs:
        if n == 1 or abs(e - 1) < 1e-12:
            out += [l / n] * n
        else:
            r = e ** (1 / (n - 1))
            d = l * (r - 1) / (r ** n - 1)
            out += [d * r ** i for i in range(n)]
    return out


def grading(secs):
    if len(secs) == 1 and secs[0][2] == 1.0:
        return "1"
    L, N = sum(s[0] for s in secs), sum(s[1] for s in secs)
    return "(" + " ".join(f"({fmt(l / L)} {fmt(n / N)} {fmt(e)})" for l, n, e in secs) + ")"


# ============================================================================= derived data
def density_coupled(cfg):
    """Salt power per mass that follows the local Boussinesq density (POWER_FOLLOWS_DENSITY)."""
    return bool(getattr(cfg, "SALT_POWER", None)) and getattr(cfg, "POWER_FOLLOWS_DENSITY", False)


def q_vol(cfg):
    """Salt heat generation per volume [W/m3]: SALT_POWER [W/g] x rho, or Q_VOL. With a power per
    mass the Boussinesq T source is SALT_POWER/cp whatever the density; the total is P x salt mass."""
    if getattr(cfg, "SALT_POWER", None):
        return cfg.SALT_POWER * 1e3 * cfg.RHO
    return cfg.Q_VOL


def patches(cfg):
    return (["innerWall"] if cfg.GEOMETRY == "A" else []) + ["outerWall", "bottom", "freeSurface"]


def h_rad(eps, Ts, Ta):
    """Linearised surface-to-ambient radiation coefficient, as externalWallHeatFluxTemperature computes it."""
    return eps * SIGMA_SB * (Ts * Ts + Ta * Ta) * (Ts + Ta)


def effective_h(spec, T):
    """Overall wall-to-ambient conductance [W/m2/K per liquid-side wall area] of a resolved
    'coefficient' boundary (radiation linearised at T)."""
    s = spec["s"]
    r = 1.0 / (s * (spec["h"] + h_rad(spec.get("emissivity", 0.0), T, spec["Ta"]))) + spec["R"]
    return 1.0 / r


def wall_radius(cfg, p):
    """(liquid-side radius, +1 cladding outside / -1 cladding inside) of a curved wall, None if flat."""
    if p == "outerWall":
        return (cfg.A_OUTER_DIAMETER if cfg.GEOMETRY == "A" else cfg.B_DIAMETER) / 2, 1
    if p == "innerWall":
        return cfg.A_INNER_DIAMETER / 2, -1
    return None


def equivalent_layers(cfg, p, layers):
    """externalWallHeatFluxTemperature treats layers as flat and puts h and the radiation on the
    liquid-side area. For a cylindrical cladding give it the exact equivalent per liquid-side area:
    thickness_i -> r_w ln(r_out,i/r_in,i) (same conduction resistance), and h, emissivity x s,
    s = r_surface/r_w (outer surface area / wall area). Returns (equivalent layers, s)."""
    geo = wall_radius(cfg, p)
    if geo is None:
        return list(layers), 1.0
    rw, sign = geo
    r, eq = rw, []
    for t, k in layers:
        r2 = r + sign * t
        if r2 <= 0:
            raise SystemExit(f"THERMAL_BC[{p}]: layers thicker than the inner radius")
        eq.append((rw * abs(math.log(r2 / r)), k))
        r = r2
    return eq, r / rw


def pick_geometry(cfg, spec):
    """Values given as {"A": ..., "B": ...} -> the one for the current geometry."""
    return {k: (v[cfg.GEOMETRY] if isinstance(v, dict) and v and set(v) <= set(GEOMETRIES) else v)
            for k, v in spec.items()}


def resolve_bcs(cfg, d):
    """Copy of THERMAL_BC for this geometry, with derived data per patch:
      coefficient : equivalent flat layers (eq_layers, R per wall area, s)
      cladding    : geometry ('cyl'/'plate'); outside 'measured' (thermocouple profile) or 'gas'
      ring        : -> flux of the ring's own heat into the salt (or the thermocouple profile, impose_tc)
    and h = 'auto' replaced by its calibrated value.

    'auto' (one gas patch, others sharing its h with h = '<patch>', the rest adiabatic/flux/ring): at
    steady state the losing walls carry all the heat that reaches them from the liquid. The gas-side h
    is chosen so that this heat leaves with the walls at the temperature implied by T_target:
        target = "liquid"    : mean liquid T;  wall T = T_target - dT_internal (Tavg - Tw_loss)
        target = "innerWall" : A axis thermocouples (mean); wall T = T_target - ring offset - dT_internal
                               (T_innerWall - Tw_loss)
        target = "wall"      : liquid side of the losing walls
        target = "surface"   : outer surface of the losing walls
    using the same wall models the BCs evaluate (bisection on h)."""
    bc = {p: pick_geometry(cfg, cfg.THERMAL_BC[p]) for p in patches(cfg)}
    for p, s in bc.items():
        if s["mode"] not in ("adiabatic", "flux", "coefficient", "balance", "cladding", "ring", "split",
                             "relative"):
            raise SystemExit(f"THERMAL_BC[{p}]: unknown mode {s['mode']}")
        if s["mode"] in ("balance", "cladding", "ring", "split") and cfg.WALL_MODEL == "shell":
            raise SystemExit(f"THERMAL_BC[{p}]: mode '{s['mode']}' needs WALL_MODEL = '1D'")
        if s["mode"] == "ring":
            if p != "innerWall":
                raise SystemExit("mode 'ring' is for the A innerWall")
            q_in, dT_tc = ring_numbers(cfg)
            s["ring"] = dict(q_in=q_in, dT_tc=dT_tc, Q=q_in * d["area"][p])
            if s.get("impose_tc"):
                s["mode"] = "ringTC"
            else:
                s["mode"], s["q_loss"] = "flux", -q_in
        if s["mode"] == "relative":
            if s.get("of") not in bc or s.get("of") == p:
                raise SystemExit(f"THERMAL_BC[{p}]: mode 'relative' needs of = '<another patch>'")
            if bc[s["of"]]["mode"] in ("relative", "split"):
                raise SystemExit(f"THERMAL_BC[{p}]: 'relative' to a '{bc[s['of']]['mode']}' patch is not supported")
            s.setdefault("ratio", 0.5)
        if s["mode"] == "cladding":
            s["geom"] = clad_geometry(cfg, p)
            if s.get("outside", "gas") not in ("gas", "measured"):
                raise SystemExit(f"THERMAL_BC[{p}]: outside must be gas or measured")
            if s.get("outside") == "measured":
                s["To_profile"] = tc_profile(cfg, "outer")
    resolve_split(cfg, d, bc)
    gas = ("coefficient", "cladding")
    for p, s in bc.items():                       # h = "<patch>": same gas (h, Ta) as that patch
        ref = s.get("h")
        if s["mode"] in gas and isinstance(ref, str) and ref != "auto":
            if ref not in bc or bc[ref]["mode"] not in gas:
                raise SystemExit(f"THERMAL_BC[{p}]: h = '{ref}' must name another coefficient/cladding patch")
            s["h_from"] = ref
            s.setdefault("Ta", bc[ref].get("Ta"))
            s["h"] = bc[ref].get("h")
    for p, s in bc.items():
        if s["mode"] == "coefficient":
            if s.get("layers") == "cladding":
                s["layers"] = cladding_layers(cfg, p)
            s["eq_layers"], s["s"] = equivalent_layers(cfg, p, s.get("layers", []))
            s["R"] = sum(t / k for t, k in s["eq_layers"])
    auto = [p for p, s in bc.items() if s["mode"] in gas and s.get("h") == "auto" and "h_from" not in s
            and s.get("outside", "gas") == "gas"]
    if not auto:
        return bc
    if len(auto) > 1 or any(s["mode"] == "balance" for s in bc.values()) \
            or any(s["mode"] in gas and p not in auto and s.get("h_from") not in auto
                   and s.get("outside", "gas") == "gas" for p, s in bc.items()):
        raise SystemExit("h = 'auto' needs one auto patch; other gas patches must share its h "
                         "(h = '<auto patch>'), the rest adiabatic, flux, ring or measured")
    pa = auto[0]
    sa = bc[pa]
    loss = [p for p, s in bc.items() if s["mode"] in gas and s.get("outside", "gas") == "gas"]
    fixed = sum(o["q_loss"] * d["area"][k] for k, o in bc.items() if o["mode"] == "flux")
    fixed -= sum(o["ring"]["Q"] for o in bc.values() if o["mode"] == "ringTC")
    Qneed = d["Qgen"] - fixed
    target = sa.get("target", "liquid")
    if target == "innerWall" and cfg.GEOMETRY != "A":
        raise SystemExit("target = 'innerWall' only exists for geometry A")
    if target not in ("liquid", "innerWall", "wall", "surface"):
        raise SystemExit(f"THERMAL_BC[{pa}]: target must be liquid, innerWall, wall or surface, not {target}")
    Tw = sa["T_target"] - (sa.get("dT_internal", 0.0) if target in ("liquid", "innerWall") else 0.0)
    if target == "innerWall" and "ring" in bc.get("innerWall", {}):
        Tw -= bc["innerWall"]["ring"]["dT_tc"]          # thermocouple reads the ring, ~0.5 K above the wall

    def patch_flux(s, h):
        """(q per wall area, wall T, outer surface T) of one losing patch for a gas-side h."""
        Ta, eps = s["Ta"], s.get("emissivity", 0.0)
        if s["mode"] == "cladding":
            g = s["geom"]
            if target == "surface":              # outer surface at the measured T
                Ts = sa["T_target"]
                r = clad_robin(cfg, s, g, Ts + 30.0, To=Ts)      # k, h_c, dT_gen at ~Ts
                qo = (h + h_rad(eps, Ts, Ta)) * (Ts - Ta)
                qi = (qo * g[2] - q_clad(cfg) * (g[2] ** 2 - g[1] ** 2) / 2) / g[1] if g[0] == "cyl" \
                    else qo - q_clad(cfg) * g[1]
                return qi, Ts + qi / r["hc"] + r["dTg"], Ts
            r = clad_robin(cfg, s, g, Tw, h=h)
            return r["qi"], Tw, r["Ts"]
        R, sc = s["R"], s["s"]
        if target == "surface":
            Ts = sa["T_target"]
            q = sc * (h + h_rad(eps, Ts, Ta)) * (Ts - Ta)
            return q, Ts + q * R, Ts
        Ts = Tw
        for _ in range(50):                      # outer surface T <-> radiation, fixed point
            q = (Tw - Ta) / (R + 1.0 / (sc * (h + h_rad(eps, Ts, Ta))))
            Ts = Tw - q * R
        return q, Tw, Ts

    def Qout(h):
        return sum(patch_flux(bc[p], h)[0] * d["area"][p] for p in loss)

    if Qout(0.0) >= Qneed:
        raise SystemExit(f"h = 'auto': radiation (and generation) alone already give {Qout(0.0):.4g} of "
                         f"{Qneed:.4g} W at the target temperature: lower the emissivity or raise Ta")
    if Qout(1e7) < Qneed:
        raise SystemExit(f"h = 'auto': even h -> infinity removes only {Qout(1e7):.4g} of {Qneed:.4g} W "
                         f"(cladding resistance / Ta too high for the target temperature)")
    lo, hi = 0.0, 1e7
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        lo, hi = (mid, hi) if Qout(mid) < Qneed else (lo, mid)
    h = 0.5 * (lo + hi)
    for p in loss:
        s = bc[p]
        s["h"] = h
        q, tw, ts = patch_flux(s, h)
        s["auto"] = dict(q=q, Tw=tw, Ts=ts, hr=h_rad(s.get("emissivity", 0.0), ts, s["Ta"]), target=target,
                         T_target=sa["T_target"], dT_internal=sa.get("dT_internal", 0.0), Q=q * d["area"][p])
    return bc


# ----------------------------------------------------------------------------- cladding with generation
def k_clad(cfg, T):
    """Hastelloy k(T): linear interpolation in CLADDING k_table, held outside it."""
    tab = cfg.CLADDING.get("k_table") or [(0.0, cfg.CLADDING["k"])]
    if T <= tab[0][0]:
        return tab[0][1]
    for (t0, k0), (t1, k1) in zip(tab, tab[1:]):
        if T <= t1:
            return k0 + (k1 - k0) * (T - t0) / (t1 - t0)
    return tab[-1][1]


def q_clad(cfg):
    """Volumetric heat generation in the cladding [W/m3] (W/g x g/m3)."""
    return cfg.CLADDING.get("generation", 0.0) * cfg.CLADDING["rho"] * 1e3


def clad_geometry(cfg, p):
    """('cyl', r_i, r_o) for the outer tube, ('plate', t) for the bottom plate."""
    c = cfg.CLADDING
    if p == "outerWall":
        ri = (cfg.A_OUTER_DIAMETER if cfg.GEOMETRY == "A" else cfg.B_DIAMETER) / 2
        return ("cyl", ri, c["outer_diameter"] / 2)
    if p == "bottom":
        return ("plate", c["bottom_thickness"])
    raise SystemExit(f"mode 'cladding' is for outerWall and bottom, not {p}")


def read_shape(cfg):
    """Side-wall flux shape q/q_mean against z/H (referenceProfiles.py -> analysis/reference_shapes.csv)."""
    path = cfg.HEAT_SPLIT["shape"]
    path = path if os.path.isabs(path) else os.path.join(HERE, path)
    zs, fs = [], []
    with open(path) as fh:
        next(fh)
        for line in fh:
            z, _, f = line.strip().split(",")
            zs.append(float(z))
            fs.append(float(f))
    return zs, fs


def mapped_shape(cfg, H, n=301):
    """Reference shape on our height: the top zone (cooled by the cladding above the liquid, an absolute
    length) keeps its thickness top_zone; the rest of the reference is stretched over the remaining height.
    Returns (z [m], q/q_mean) on n points."""
    zs, fs = read_shape(cfg)
    hs = cfg.HEAT_SPLIT
    Hr, Zt = hs.get("ref_height", 36e-3), min(hs.get("top_zone", 0.0), 0.5 * H)
    zeta_t = 1.0 - Zt / Hr

    def f_at(zeta):
        for i in range(1, len(zs)):
            if zeta <= zs[i]:
                return fs[i - 1] + (fs[i] - fs[i - 1]) * (zeta - zs[i - 1]) / (zs[i] - zs[i - 1])
        return fs[-1]

    out_z, out_f = [], []
    for i in range(n):
        z = H * i / (n - 1)
        zeta = zeta_t * z / (H - Zt) if z < H - Zt else zeta_t + (z - (H - Zt)) / Hr
        out_z.append(z)
        out_f.append(f_at(min(max(zeta, 0.0), 1.0)))
    return out_z, out_f


def resolve_split(cfg, d, bc):
    """mode 'split': the heat leaving the salt (generation + ring heat - other fixed fluxes) is shared
    between the side wall, bottom and free surface by mean-flux ratios (HEAT_SPLIT), the side with the
    reference shape along z. Bottom/top become uniform power-mode fluxes, the side a coded shaped flux.
    All totals are normalised on the mesh, so the balance is exact."""
    split = [p for p, s in bc.items() if s["mode"] == "split"]
    if not split:
        return
    if "outerWall" not in split:
        raise SystemExit("mode 'split' needs the outerWall in the split")
    bad = [p for p, s in bc.items() if s["mode"] in ("coefficient", "cladding", "balance")]
    if bad:
        raise SystemExit(f"mode 'split' takes all the heat: {bad} must be adiabatic, flux or ring")
    hs = cfg.HEAT_SPLIT
    w = {"outerWall": 1.0, "bottom": hs["bottom_over_side"],
         "freeSurface": hs["bottom_over_side"] * hs["top_over_bottom"]}
    for p_ in split:
        if p_ not in w:
            raise SystemExit(f"mode 'split' is for outerWall, bottom and freeSurface, not {p_}")
    fixed = sum(o["q_loss"] * d["area"][k] for k, o in bc.items() if o["mode"] == "flux")
    fixed -= sum(o["ring"]["Q"] for o in bc.values() if o["mode"] == "ringTC")
    Qout = d["Qgen"] - fixed
    q_side = Qout / sum(w[p_] * d["area"][p_] for p_ in split)
    for p_ in split:
        s = bc[p_]
        s["split"] = dict(weight=w[p_], q=w[p_] * q_side, Q=w[p_] * q_side * d["area"][p_],
                          share=w[p_] * q_side * d["area"][p_] / Qout)
        if p_ == "outerWall":
            s["shape"] = mapped_shape(cfg, d["H"])
        else:
            s["mode"], s["q_loss"] = "flux", w[p_] * q_side


def ring_numbers(cfg):
    """A inner ring (r_a -> r_b, closed inside): flux of its own heat into the salt at r_b, and
    T(r_a) - T(r_b), the thermocouple reading minus the inner-wall T."""
    ra, rb = cfg.CLADDING["inner_ring_diameter"] / 2, cfg.A_INNER_DIAMETER / 2
    qc, k = q_clad(cfg), k_clad(cfg, cfg.T_REF)
    q_in = qc * (rb ** 2 - ra ** 2) / (2 * rb)
    dT_tc = qc / (4 * k) * (rb ** 2 - ra ** 2) - qc * ra ** 2 / (2 * k) * math.log(rb / ra)
    return q_in, dT_tc


def clad_robin(cfg, s, geom, Tw, h=None, To=None):
    """Steady radial conduction with generation q_c through the cladding, liquid-side wall at Tw.
    Returns dict(H, Tref, qi, qo, Ts): q_i = H (Tw - Tref) leaves the liquid (per wall area),
    q_o leaves the outer surface (per outer area) at T_s. The coded BC evaluates the same formulas.
      cylinder r_i -> r_o:  h_c = k/(r_i ln(r_o/r_i)),  dT_gen = q_c/(4k) [r_o^2 - r_i^2 - 2 r_i^2 ln(r_o/r_i)]
                            q_o r_o = q_i r_i + q_c (r_o^2 - r_i^2)/2
      plate t:              h_c = k/t,                dT_gen = q_c t^2/(2k),  q_o = q_i + q_c t
      measured T_o:  H = h_c,  Tref = T_o + dT_gen
      gas h, Ta:     T_o = Ta + q_o/h_g, h_g = h + h_rad(T_o)  ->  H, Tref with the generation folded in"""
    qc, eps = q_clad(cfg), s.get("emissivity", 0.0)
    Ts = To if To is not None else Tw - 20.0
    for _ in range(60):
        k = k_clad(cfg, 0.5 * (Tw + Ts))
        if geom[0] == "cyl":
            _, ri, ro = geom
            L = math.log(ro / ri)
            hc = k / (ri * L)
            dTg = qc / (4 * k) * (ro ** 2 - ri ** 2 - 2 * ri ** 2 * L)
            extra, ratio = qc * (ro ** 2 - ri ** 2) / (2 * ro), ri / ro
        else:
            t = geom[1]
            hc, dTg, extra, ratio = k / t, qc * t ** 2 / (2 * k), qc * t, 1.0
        if To is not None:
            H, Tref = hc, To + dTg
        else:
            hg = h + h_rad(eps, Ts, s["Ta"])
            H = 1.0 / (1.0 / hc + ratio / hg)
            Tref = s["Ta"] + dTg + extra / hg
        qi = H * (Tw - Tref)
        qo = qi * ratio + extra
        if To is None:
            Ts = s["Ta"] + qo / hg
    return dict(H=H, Tref=Tref, qi=qi, qo=qo, Ts=Ts, k=k, hc=hc, dTg=dTg)


def clad_heat(cfg, d, p):
    """Heat generated in the cladding behind a 'cladding' patch [W] (plate: under the liquid only)."""
    g = d["bc"][p]["geom"]
    if g[0] == "cyl":
        return q_clad(cfg) * math.pi * (g[2] ** 2 - g[1] ** 2) * d["H"]
    return q_clad(cfg) * g[1] * d["area"][p]


def tc_profile(cfg, kind):
    """Thermocouple profile T(z) [K]: kind 'axis' (A, inside the inner ring) or 'outer' (cladding surface)."""
    data = (cfg.THERMOCOUPLES.get(cfg.GEOMETRY) or {}).get(kind)
    if not data:
        raise SystemExit(f"no '{kind}' thermocouple readings for geometry {cfg.GEOMETRY} (THERMOCOUPLES)")
    return profile(data["z"], data["T"], cfg.TC_PROFILE)


def cladding_layers(cfg, p):
    """[(thickness, k)] of the Hastelloy cladding behind a patch."""
    c = cfg.CLADDING
    if p == "outerWall":
        rw = (cfg.A_OUTER_DIAMETER if cfg.GEOMETRY == "A" else cfg.B_DIAMETER) / 2
        t = c["outer_diameter"] / 2 - rw
    elif p == "innerWall":
        t = cfg.A_INNER_DIAMETER / 2 - c["inner_ring_diameter"] / 2
    elif p == "bottom":
        t = c["bottom_thickness"]
    else:
        raise SystemExit(f"no cladding behind {p}")
    if t <= 0:
        raise SystemExit(f"cladding behind {p} has thickness {t}")
    return [(t, c["k"])]


def build_mesh(cfg):
    lvl = MESH_LEVELS[cfg.MESH_LEVEL]
    h, dz = lvl["h"], lvl["dz"]
    bl = cfg.BOUNDARY_LAYER
    d1, r = cfg.BL_FIRST_CELL, cfg.BL_GROWTH
    top_bl = bl and pick_geometry(cfg, cfg.THERMAL_BC["freeSurface"])["mode"] != "adiabatic"
    m = {}
    if is_wedge(cfg):                           # axisymmetric: one cell around, radial x axial only
        H = cfg.A_HEIGHT if cfg.GEOMETRY == "A" else cfg.B_HEIGHT
        if cfg.GEOMETRY == "A":
            ri, ro = cfg.A_INNER_DIAMETER / 2, cfg.A_OUTER_DIAMETER / 2
            m["rad"], m["Nr"] = graded(ro - ri, h, d1, r, bl, bl)      # inner wall -> outer wall
        else:
            m["rad"], m["Nr"] = graded(cfg.B_DIAMETER / 2, h, d1, r, False, bl)   # axis -> wall
        m["ax"], m["Nz"] = graded(H, dz, d1, r, bl, top_bl)
        m["cells"] = m["Nr"] * m["Nz"]
        m["wall_rad"] = cell_sizes(m["rad"])[::-1]
        m["first_rad"] = m["wall_rad"][0]
        m["first_ax"] = cell_sizes(m["ax"])[0]
        return m
    if cfg.GEOMETRY == "A":
        ri, ro, H = cfg.A_INNER_DIAMETER / 2, cfg.A_OUTER_DIAMETER / 2, cfg.A_HEIGHT
        m["rad"], m["Nr"] = graded(ro - ri, h, d1, r, bl, bl)
        m["Nt"] = math.ceil(0.5 * math.pi * 0.5 * (ri + ro) / h - 1e-9)
        m["ax"], m["Nz"] = graded(H, dz, d1, r, bl, top_bl)
        m["cells"] = 4 * m["Nt"] * m["Nr"] * m["Nz"]
        m["wall_rad"] = cell_sizes(m["rad"])[::-1]        # outer wall -> inward
    else:
        R, H = cfg.B_DIAMETER / 2, cfg.B_HEIGHT
        s, ra = cfg.B_CORE_HALF_SIDE * R, cfg.B_CORE_ARC_RADIUS * R
        m["Nc"] = math.ceil(0.5 * math.pi * R / h - 1e-9)
        m["rad"], m["Nr"] = graded(R - ra, h, d1, r, bl, False)    # wall -> core
        m["ax"], m["Nz"] = graded(H, dz, d1, r, bl, top_bl)
        m["cells"] = (m["Nc"] ** 2 + 4 * m["Nc"] * m["Nr"]) * m["Nz"]
        m["wall_rad"] = cell_sizes(m["rad"])
        m["core"] = 2 * s / m["Nc"]
    m["first_rad"] = m["wall_rad"][0]
    m["first_ax"] = cell_sizes(m["ax"])[0]
    return m


def derive(cfg):
    d = {}
    vis = cfg.VISCOSITY
    if vis["model"] == "arrhenius":
        # mu = mu0 exp(Ea/(R T)); OpenFOAM's ArrheniusNewtonian is nu = nuRef exp(-alpha (T - Talpha)):
        # tangent at TRef (same value and slope), alpha = Ea/(R TRef^2)
        d["mu"] = vis["mu0"] * math.exp(vis["Ea"] / (R_GAS * cfg.T_REF))
        d["alpha_mu"] = vis["Ea"] / (R_GAS * cfg.T_REF ** 2)
    elif vis["model"] == "constant":
        d["mu"] = cfg.MU
    else:
        raise SystemExit(f"VISCOSITY model must be constant or arrhenius, not {vis['model']}")
    nu, a = d["mu"] / cfg.RHO, cfg.K / (cfg.RHO * cfg.CP)
    d.update(nu=nu, a=a, Pr=nu / a)
    if cfg.GEOMETRY == "A":
        ri, ro, H = cfg.A_INNER_DIAMETER / 2, cfg.A_OUTER_DIAMETER / 2, cfg.A_HEIGHT
        Aend = math.pi * (ro ** 2 - ri ** 2)
        d["area"] = dict(innerWall=2 * math.pi * ri * H, outerWall=2 * math.pi * ro * H, bottom=Aend, freeSurface=Aend)
        d["L"] = 0.5 * (ro - ri)                   # half-gap: conduction length
    else:
        R, H = cfg.B_DIAMETER / 2, cfg.B_HEIGHT
        Aend = math.pi * R ** 2
        d["area"] = dict(outerWall=2 * math.pi * R * H, bottom=Aend, freeSurface=Aend)
        d["L"] = R
    d["H"] = H
    d["V"] = Aend * H
    d["Qgen"] = q_vol(cfg) * d["V"]
    d["ST"] = q_vol(cfg) / (cfg.RHO * cfg.CP)       # T source [K/s]

    # lumped energy balance: Qgen = sum(G_i (T - Ta_i)) + sum(P_i)
    # flux / balance patches are written as total powers P_i so that the balance is exact on the mesh
    d["bc"] = bc = resolve_bcs(cfg, d)
    Gc = GTa = Qflux = 0.0
    d["power"] = {}
    for p in patches(cfg):
        spec = bc[p]
        if spec["mode"] == "coefficient":
            he = effective_h(spec, cfg.T_INIT)
            Gc += he * d["area"][p]
            GTa += he * d["area"][p] * spec["Ta"]
        elif spec["mode"] == "cladding":                 # Robin q = H (T - Tref), linearised at T_INIT
            if spec.get("outside") == "measured":
                zt, Tt = profile_table(cfg, spec["To_profile"])
                r = clad_robin(cfg, spec, spec["geom"], cfg.T_INIT, To=sum(Tt) / len(Tt))
            else:
                r = clad_robin(cfg, spec, spec["geom"], cfg.T_INIT, h=spec["h"])
            spec["robin"] = r
            Gc += r["H"] * d["area"][p]
            GTa += r["H"] * d["area"][p] * r["Tref"]
        elif spec["mode"] == "split":
            d["power"][p] = spec["split"]["Q"]
            Qflux += d["power"][p]
        elif spec["mode"] == "ringTC":                   # heat in ~ the ring's own generation
            d["power"][p] = -spec["ring"]["Q"]
            Qflux += d["power"][p]
        elif spec["mode"] == "flux":
            d["power"][p] = spec["q_loss"] * d["area"][p]
            Qflux += d["power"][p]
    for p in patches(cfg):
        if bc[p]["mode"] == "balance":                   # removes whatever the other patches do not
            d["power"][p] = d["Qgen"] - Qflux
            Qflux = d["Qgen"]
    d["Qflux"] = Qflux
    d["all_flux"] = Gc == 0
    d["T_ss"] = (GTa + d["Qgen"] - Qflux) / Gc if Gc > 0 else None
    d["tau"] = cfg.RHO * cfg.CP * d["V"] / Gc if Gc > 0 else None

    # internal-heating Rayleigh number on the conduction length and a conduction temperature scale
    d["Ra_I"] = G * cfg.BETA * q_vol(cfg) * d["L"] ** 5 / (nu * a * cfg.K)
    d["dT_cond"] = q_vol(cfg) * d["L"] ** 2 / (2 * cfg.K)
    # temperature scale -> laminar vertical boundary layer delta ~ H Ra_H^-1/4
    dT = max(d["dT_cond"], 1.0)
    d["Ra_H"] = G * cfg.BETA * dT * H ** 3 / (nu * a)
    d["delta"] = H * d["Ra_H"] ** -0.25
    if radiation_on(cfg):
        a_abs = cfg.RADIATION["absorption"]
        d["L_opt"] = (cfg.A_OUTER_DIAMETER - cfg.A_INNER_DIAMETER) / 2 if cfg.GEOMETRY == "A" else cfg.B_DIAMETER
        d["tau_opt"] = a_abs * d["L_opt"]
        # optically thick (Rosseland) limit: radiation acts as an extra conductivity
        d["k_rad"] = 16 * SIGMA_SB * cfg.T_REF ** 3 / (3 * a_abs)
    d["mesh"] = build_mesh(cfg)
    m = d["mesh"]
    cum, n = 0.0, 0
    for s in m["wall_rad"]:
        cum += s
        if cum > d["delta"]:
            break
        n += 1
    d["cells_in_delta"] = n
    return d


def checks(cfg, d):
    w = []
    modes = [d["bc"][p]["mode"] for p in patches(cfg)]
    if modes.count("balance") > 1:
        raise SystemExit("THERMAL_BC: only one patch can use mode 'balance'")
    if d["all_flux"] and abs(d["Qgen"] - d["Qflux"]) > 1e-9 * max(d["Qgen"], 1e-30):
        w.append(f"only flux/adiabatic boundaries and Qgen - Qout = {d['Qgen'] - d['Qflux']:.4g} W: "
                 "no steady state exists, the mean T drifts (use mode 'balance' on one patch)")
    for p, P in d["power"].items():
        if d["bc"][p]["mode"] == "balance" and P < 0:
            w.append(f"{p} (balance) has to supply {-P:.3g} W: the other losses exceed Qgen")
    if d["T_ss"] is not None and cfg.BETA * abs(d["T_ss"] - cfg.T_REF) > 0.05:
        w.append(f"beta*|T_ss - TRef| = {cfg.BETA * abs(d['T_ss'] - cfg.T_REF):.3f}: Boussinesq is getting "
                 f"marginal; set T_REF closer to the expected mean temperature ({d['T_ss']:.1f} K)")
    if d["Ra_I"] > 1e7:
        w.append(f"Ra_I = {d['Ra_I']:.2e}: flow may be unsteady/transitional, laminar assumption doubtful")
    if d["cells_in_delta"] < 4:
        w.append(f"only {d['cells_in_delta']} cells across the estimated thermal boundary layer "
                 f"({1e3 * d['delta']:.2f} mm): consider BOUNDARY_LAYER = True or a finer mesh")
    if radiation_on(cfg) and cfg.RADIATION["model"] == "P1" and d["tau_opt"] < 3:
        w.append(f"optical thickness a*L = {d['tau_opt']:.2g}: P1 is inaccurate for optically thin media, "
                 "prefer fvDOM (or check P1 against it once)")
    if d["mesh"]["cells"] > 2e6:
        w.append(f"{d['mesh']['cells'] / 1e6:.1f} M cells")
    pp = getattr(cfg, "PARTICLES", {})
    if pp.get("enabled"):
        if "transient" not in stages(cfg):
            w.append("PARTICLES enabled but RUN_MODE is 'steady': the cloud needs the transient stage, not written")
        elif not 0 < pp["SOI"] < cfg.TRANSIENT_END_TIME:
            raise SystemExit("PARTICLES['SOI'] must lie inside the transient stage (0 < SOI < TRANSIENT_END_TIME): "
                             "the cloud is built at the 2nd time step")
        if pp["SOI"] + (pp.get("release_duration", 0) or 0) > cfg.TRANSIENT_END_TIME:
            w.append("PARTICLES: SOI + release_duration is after TRANSIENT_END_TIME: not all parcels get released")
        if pp.get("injection") == "cellZone" and (pp.get("release_duration", 0) or 0) > 0:
            w.append("PARTICLES injection 'cellZone': cellZoneInjection releases all parcels at SOI "
                     "(release_duration is ignored); the number per size is ~n_per_injection (rounded per cell)")
        if pp.get("brownian", "BoundedBrownianMotion") == "BoundedBrownianMotion":
            w.append("BoundedBrownianMotion: for dt >> tauP the parcel diffusivity is dt/(2 tauP) x Stokes-Einstein "
                     "(and sub-100 nm parcels get ~thermal speed -> very slow); stock 'BrownianMotion' is exact there "
                     "(see README)")
        if pp.get("u_integration", "CrankNicolson") == "CrankNicolson":
            w.append("U integration CrankNicolson does not damp the slip when dt >> tauP (amplification -> -1): "
                     "use 'analytical' (see README)")
    return w


