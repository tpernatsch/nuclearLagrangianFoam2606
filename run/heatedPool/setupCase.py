def level_pin(cfg, d):
    """Flux-only boundaries: the level comes from LEVEL_PIN ('innerWallTC': A inner-wall mean at the
    axis thermocouple spline mean minus the ring offset; 'volume': volume mean at T_INIT)."""
    how = pick_geometry(cfg, dict(x=getattr(cfg, "LEVEL_PIN", "volume")))["x"]
    if how == "innerWallTC":
        if cfg.GEOMETRY != "A":
            raise SystemExit("LEVEL_PIN 'innerWallTC' is for geometry A")
        zt, Tt = profile_table(cfg, tc_profile(cfg, "axis"), n=301)
        target = sum(Tt) / len(Tt) - d["bc"]["innerWall"].get("ring", {}).get("dT_tc", 0.0)
        what, patch = "the inner-wall mean (axis thermocouple spline mean - ring offset)", "innerWall"
    elif how == "volume":
        target, what, patch = cfg.T_INIT, "the volume mean", ""
    else:
        raise SystemExit(f"LEVEL_PIN must be innerWallTC or volume, not {how}")
    d["pin"] = dict(how=how, target=target)
    return (MEAN_T_PIN.replace("@TARGET@", f"{target:.10g}").replace("@PATCH@", patch)
            .replace("@WHAT@", what))


