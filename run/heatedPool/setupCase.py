# ============================================================================= fields
def radiation_on(cfg):
    return cfg.RADIATION.get("model", "none") != "none"


def is_wedge(cfg):
    return getattr(cfg, "MESH_TYPE", "3D") == "wedge"


def wedge_frac(cfg):
    """Fraction of the full capsule the mesh holds (wedge angle / 360, or 1)."""
    return getattr(cfg, "WEDGE_ANGLE", 5.0) / 360.0 if is_wedge(cfg) else 1.0


def shell_patches(cfg):
    """Cladding walls carrying the thin-shell model (WALL_MODEL = 'shell'). blockMesh creates them as
    patches; they are merged into ONE patch 'cladding' (one shell BC -> one shell solve per iteration)
    and kept as faceZones of the same names for the per-wall losses and heat balance."""
    if cfg.WALL_MODEL != "shell":
        return []
    return [p for p in patches(cfg) if p != "freeSurface"]


def fluid_patches(cfg):
    """Patches of the final mesh (after the cladding walls are merged in the shell model)."""
    return ["cladding", "freeSurface"] if shell_patches(cfg) else patches(cfg)


def shell_thickness(cfg, p):
    """Shell thickness hs: the cladding thickness x r_mean/r_wall for a tube, so that the axial
    conductance (k hs 2 pi r_w) and heat capacity of the shell equal those of the thick tube."""
    t = cladding_layers(cfg, p)[0][0]
    geo = wall_radius(cfg, p)
    if geo is None:
        return t
    rw, sign = geo
    return t * (rw + sign * t / 2) / rw


def external_coefficient(cfg, s):
    """Liquid-side wall -> gas conductance per wall area: cladding through-wall resistance in series
    with gas convection + radiation (linearised at the outer-surface T) on the larger outer area."""
    Ts = s["auto"]["Ts"] if "auto" in s else cfg.T_REF
    return 1.0 / (s["R"] + 1.0 / (s["s"] * (s["h"] + h_rad(s.get("emissivity", 0.0), Ts, s["Ta"]))))


def cxx_list(values, fmt_="{:.10g}"):
    return "{" + ", ".join(fmt_.format(v) for v in values) + "}"


def profile_table(cfg, prof, n=101):
    """The thermocouple profile sampled for the coded BCs (linear in between, held outside)."""
    H = cfg.A_HEIGHT if cfg.GEOMETRY == "A" else cfg.B_HEIGHT
    z = [H * i / (n - 1) for i in range(n)]
    return z, [prof(v) for v in z]


def cladding_bc(cfg, d, p, s):
    """Coded Robin condition for a cladding wall with heat generation (see clad_robin)."""
    g = s["geom"]
    kT, kK = zip(*(cfg.CLADDING.get("k_table") or [(0.0, cfg.CLADDING["k"])]))
    measured = s.get("outside") == "measured"
    lines = [f"const scalar qc = {q_clad(cfg):.10g};      // cladding heat generation [W/m3]",
             f"const scalar kf = {cfg.K:.10g};          // salt conductivity [W/m/K]",
             f"const scalarField kT({cxx_list(kT)});",
             f"const scalarField kK({cxx_list(kK)});      // Hastelloy k(T)"]
    if g[0] == "cyl":
        lines.append(f"const scalar ri = {g[1]:.10g}, ro = {g[2]:.10g};   // liquid side / outer surface radius")
    else:
        lines.append(f"const scalar t = {g[1]:.10g};      // plate thickness")
    if measured:
        zt, Tt = profile_table(cfg, s["To_profile"])
        lines += [f"const scalarField zTC({cxx_list(zt)});",
                  f"const scalarField TTC({cxx_list(Tt)});    // outer-surface thermocouple profile [K]"]
    else:
        lines.append(f"const scalar Ta = {s['Ta']:.10g}, h = {s['h']:.10g}, eps = {s.get('emissivity', 0.0):.10g};"
                     f"   // gas, per outer area")
    geo_code = ("""            const scalar L = log(ro/ri);
            const scalar hc = k/(ri*L);
            const scalar dTg = qc/(4*k)*(sqr(ro) - sqr(ri) - 2*sqr(ri)*L);
            const scalar extra = qc*(sqr(ro) - sqr(ri))/(2*ro);
            const scalar ratio = ri/ro;""" if g[0] == "cyl" else """            const scalar hc = k/t;
            const scalar dTg = qc*sqr(t)/(2*k);
            const scalar extra = qc*t;
            const scalar ratio = 1;""")
    side_code = ("""            H = hc;
            Tref = To + dTg;""" if measured else """            const scalar hg = h + eps*5.670374419e-8*(sqr(Ts) + sqr(Ta))*(Ts + Ta);
            H = 1/(1/hc + ratio/hg);
            Tref = Ta + dTg + extra/hg;
            Ts = Ta + (H*(Tw[i] - Tref)*ratio + extra)/hg;""")
    start = "const scalar To = interpolateXY(zf[i], zTC, TTC);\n        scalar Ts = To;" if measured \
        else "scalar Ts = Tw[i] - 20;"
    doc = (f"Cladding {p}: steady radial conduction with generation, "
           + ("thermocouple profile on the outer surface" if measured else "gas convection + radiation outside"))
    code = f"""
// {doc}
//   q_liquid = H (T_w - T_ref):  refValue = T_ref, valueFraction = H/(H + k_f deltaCoeffs)
{chr(10).join(lines)}

const scalarField Tw(*this);                 // wall T of the previous iteration (k(T), radiation)
const scalarField zf(this->patch().Cf().component(vector::Z));
const scalarField& dc = this->patch().deltaCoeffs();
scalarField& rv = this->refValue();
scalarField& vf = this->valueFraction();

forAll(Tw, i)
{{
    {start}
    scalar H = 0, Tref = Tw[i];
    for (label it = 0; it < 20; ++it)
    {{
        const scalar k = interpolateXY(0.5*(Tw[i] + Ts), kT, kK);
{geo_code}
{side_code}
    }}
    rv[i] = Tref;
    vf[i] = H/(H + kf*dc[i]);
}}
this->refGrad() = Zero;
"""
    return (f"type            codedMixed;\n"
            f"name            cladding_{p};\n"
            f"refValue        $internalField;\n"
            f"refGradient     uniform 0;\n"
            f"valueFraction   uniform 0;\n"
            f"value           $internalField;\n\n"
            f"codeInclude\n#{{\n    #include \"interpolateXY.H\"\n#}};\n\n"
            f"code\n#{{{indent(code, 4)}\n#}};")


def split_bc(cfg, d, p, s):
    """Side wall of mode 'split': prescribed heat Q distributed along z with the reference shape."""
    zs, fs = s["shape"]
    Q = s["split"]["Q"] * wedge_frac(cfg)
    return (f"type            codedMixed;\n"
            f"name            shapedFlux_{p};\n"
            f"refValue        $internalField;\n"
            f"refGradient     uniform 0;\n"
            f"valueFraction   uniform 0;\n"
            f"value           $internalField;\n\n"
            f"codeInclude\n#{{\n    #include \"interpolateXY.H\"\n#}};\n\n"
            f"code\n#{{\n"
            f"    // {Q:.6g} W leave through {p} ({100 * s['split']['share']:.2f} % of the heat leaving the salt),\n"
            f"    // distributed along z with the reference flux shape "
            f"(top zone {1e3 * cfg.HEAT_SPLIT.get('top_zone', 0):g} mm kept absolute)\n"
            f"    const scalar Q = {Q:.12g}, kf = {cfg.K:.10g};\n"
            f"    const scalarField zs({cxx_list(zs)});\n"
            f"    const scalarField fs({cxx_list(fs)});\n"
            f"    const scalarField zf(this->patch().Cf().component(vector::Z));\n"
            f"    const scalarField& sf = this->patch().magSf();\n"
            f"    const scalarField f(interpolateXY(zf, zs, fs));\n"
            f"    const scalar norm = gSum(f*sf);            // exact total on this mesh\n"
            f"    this->refGrad() = -Q*f/(max(norm, VSMALL)*kf);\n"
            f"    this->refValue() = *this;\n"
            f"    this->valueFraction() = 0;\n#}};")


def relative_bc(cfg, d, p, s):
    """Heat flux out of p = ratio x the current mean heat flux out of patch 'of' (per area, lagged one
    iteration). Conduction flux, k_salt snGrad(T), the same as heatBalance reports."""
    return (f"type            codedMixed;\n"
            f"name            relativeFlux_{p};\n"
            f"refValue        $internalField;\n"
            f"refGradient     uniform 0;\n"
            f"valueFraction   uniform 0;\n"
            f"value           $internalField;\n\n"
            f"code\n#{{\n"
            f"    // heat flux out of {p} = {s['ratio']:g} x mean heat flux out of {s['of']} (per area)\n"
            f"    const scalar ratio = {s['ratio']:.10g}, kf = {cfg.K:.10g};\n"
            f"    const volScalarField& T = this->db().template lookupObject<volScalarField>(\"T\");\n"
            f"    const label pi = this->patch().boundaryMesh().findPatchID(\"{s['of']}\");\n"
            f"    const fvPatchScalarField& Tp = T.boundaryField()[pi];\n"
            f"    const scalarField& sf = Tp.patch().magSf();\n"
            f"    const scalar qOf = -kf*gSum(Tp.snGrad()*sf)/max(gSum(sf), VSMALL);   // > 0 = out\n"
            f"    this->refGrad() = -ratio*qOf/kf;\n"
            f"    this->refValue() = *this;\n"
            f"    this->valueFraction() = 0;\n#}};")


def ring_tc_bc(cfg, d, s):
    """A inner wall at the axis thermocouple profile minus the ring offset (fixed value)."""
    zt, Tt = profile_table(cfg, tc_profile(cfg, "axis"))
    dT = s["ring"]["dT_tc"]
    return (f"type            codedFixedValue;\n"
            f"name            ringThermocouples;\n"
            f"value           $internalField;\n\n"
            f"codeInclude\n#{{\n    #include \"interpolateXY.H\"\n#}};\n\n"
            f"code\n#{{\n"
            f"    // axis thermocouples (spline) minus the ring conduction offset {dT:.4g} K\n"
            f"    const scalarField zTC({cxx_list(zt)});\n"
            f"    const scalarField TTC({cxx_list(Tt)});\n"
            f"    const scalarField zf(this->patch().Cf().component(vector::Z));\n"
            f"    operator==(interpolateXY(zf, zTC, TTC) - {dT:.10g});\n#}};")


def t_bc(cfg, d, p):
    rad = radiation_on(cfg)
    if p in d["bc"] and d["bc"][p]["mode"] == "cladding":
        return cladding_bc(cfg, d, p, d["bc"][p])
    if p in d["bc"] and d["bc"][p]["mode"] == "ringTC":
        return ring_tc_bc(cfg, d, d["bc"][p])
    if p in d["bc"] and d["bc"][p]["mode"] == "split":
        return split_bc(cfg, d, p, d["bc"][p])
    if p in d["bc"] and d["bc"][p]["mode"] == "relative":
        return relative_bc(cfg, d, p, d["bc"][p])
    if p == "cladding":
        c = cfg.CLADDING
        return (f"type            compressible::thermalShell;   // wall T = shell T (system/finite-area)\n"
                f"thermalShellModel thermalShell;\n"
                f"region          shell;\n"
                f"active          true;\n"
                f"thermo\n{{\n    rho         {fmt(c['rho'])};\n    kappa       {fmt(c['k'])};\n"
                f"    Cp          {fmt(c['cp'])};\n    emissivity  0;\n}}\n"
                f"h               hs;\n"
                + ("qr              qr;\n" if rad else "")
                + "value           $internalField;")
    spec = d["bc"][p]
    mode = spec["mode"]
    if mode == "adiabatic" and not rad:
        return "type            zeroGradient;"
    kappa = (f"kappaMethod     function;      // no thermo in the Boussinesq solvers: constant kappa\n"
             f"kappaValue      constant {fmt(cfg.K)};\n"
             f"alphaValue      constant {fmt(cfg.K / cfg.CP)};")
    if rad:     # radiation absorbed at the wall (qr > 0 = into the wall) enters the wall heat balance
        kappa += "\nqr              qr;"
    if mode == "adiabatic":
        # no external loss: what the wall absorbs as radiation goes back into the liquid by
        # conduction (re-radiating wall, net heat flow zero)
        return (f"type            externalWallHeatFluxTemperature;\n"
                f"mode            flux;         // adiabatic, re-radiating\n"
                f"q               constant 0;\n"
                f"{kappa}\nvalue           $internalField;")
    if mode in ("flux", "balance"):
        # a total power spread uniformly over the patch = a constant flux whose integral
        # matches the absolute heat source exactly on the discrete mesh
        P = d["power"][p]
        what = ("removes the generated heat not lost elsewhere" if mode == "balance"
                else f"q_loss = {spec['q_loss']:g} W/m2 x nominal area {d['area'][p]:.5g} m2")
        return (f"type            externalWallHeatFluxTemperature;\n"
                f"mode            power;        // uniform flux = Q / patch area\n"
                f"Q               constant {-P * wedge_frac(cfg):.12g};   // W, > 0 heats the liquid ({what})"
                + (f" x wedge {wedge_frac(cfg):.6g}" if is_wedge(cfg) else "") + "\n"
                f"{kappa}\nvalue           $internalField;")
    layers, sc = spec["eq_layers"], spec["s"]
    lay = ""
    if layers:
        lay = (f"thicknessLayers ({' '.join(f'{t:.6g}' for t, _ in layers)});\n"
               f"kappaLayers     ({' '.join(fmt(k) for _, k in layers)});\n")
    eps = spec.get("emissivity", 0.0)
    head = ""
    if sc != 1.0:
        real = ", ".join(f"{1e3 * t:g} mm @ {k:g} W/m/K" for t, k in spec.get("layers", []))
        head = (f"// Cylindrical cladding ({real}) written as its exact flat equivalent per liquid-side area:\n"
                f"// thickness -> r_w ln(r_out/r_in); h and emissivity x r_surface/r_w = {sc:.5g}.\n"
                f"// Real values: h = {spec['h']:.6g} W/m2/K, emissivity = {eps:g} on the outer surface.\n")
    note = ""
    if "auto" in spec:
        note = f"   // calibrated: T_target {spec['auto']['T_target']:g} K ({spec['auto']['target']})"
    return (f"{head}type            externalWallHeatFluxTemperature;\n"
            f"mode            coefficient;  // cladding layers + gas convection h + radiation to Ta\n"
            f"h               constant {sc * spec['h']:.6g};{note}\n"
            f"Ta              constant {fmt(spec['Ta'])};\n"
            f"emissivity      {sc * eps:.6g};\n"
            f"{lay}{kappa}\nvalue           $internalField;")


