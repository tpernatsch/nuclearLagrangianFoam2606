def fv_solution(stage, all_flux, wedge=False):
    solvers = """
solvers
{
    p_rgh
    {
        solver          GAMG;
        smoother        DICGaussSeidel;
        tolerance       1e-9;
        relTol          %s;
    }

    p_rghFinal
    {
        $p_rgh;
        relTol          0;
    }

    U
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-10;
        relTol          0.1;
    }

    T
    {
%s
    }

    "(U|T)Final"
    {
        $U;
        relTol          0;
    }

    G                   // P1 radiation (unused otherwise)
    {
        solver          GAMG;
        smoother        symGaussSeidel;
        tolerance       1e-8;
        relTol          0.01;
    }

    Ii                  // fvDOM ray intensities (unused otherwise)
    {
        solver          GAMG;
        smoother        symGaussSeidel;
        tolerance       1e-4;
        relTol          0;
        maxIter         5;
        nPostSweeps     1;
    }
}
"""
    # steady: the mean temperature level is a global (low-frequency) mode that Gauss-Seidel
    # barely touches -> multigrid for T, otherwise the heat balance takes ages to close
    t_steady = indent("""
solver          GAMG;
smoother        symGaussSeidel;
tolerance       1e-10;
relTol          0.01;""", 8)
    t_transient = indent("""
solver          smoothSolver;
smoother        symGaussSeidel;
tolerance       1e-10;
relTol          0.1;""", 8)
    if all_flux:    # T level set by the flux balance only: the matrix is singular, relaxation anchors
        t_relax = "0.9;    // < 1 anchors the mean T (flux-only boundaries leave its level free)"
    else:           # < 1 would freeze the mean: its only restoring force is the weak wall loss (1/tau)
        t_relax = "1;"
    if stage == "steady":
        return solvers % ("0.05", t_steady) + """
SIMPLE
{
    momentumPredictor       yes;
    nNonOrthogonalCorrectors 1;
    pRefCell                0;      // closed domain: pressure level fixed here
    pRefValue               0;

    residualControl
    {
        p_rgh               1e-6;
        U                   @UTOL@
        T                   1e-8;
    }
}

relaxationFactors
{
    fields
    {
        p_rgh               0.7;
    }
    equations
    {
        U                   0.3;
        T                   @TRELAX@
    }
}
""".replace("@TRELAX@", t_relax).replace("@UTOL@", "5e-6;   // wedge: the azimuthal component (U ~ 0) stalls at ~1e-6" if wedge else "1e-7;")
    return solvers % ("0.01", t_transient) + """
PIMPLE
{
    momentumPredictor       yes;    // buoyancy-driven: keep the momentum predictor
    nOuterCorrectors        1;
    nCorrectors             2;
    nNonOrthogonalCorrectors 1;
    pRefCell                0;      // closed domain: pressure level fixed here
    pRefValue               0;
}

relaxationFactors
{
    equations
    {
        ".*"                1;
    }
}
"""


def stages(cfg):
    return {"steady": ["steady"], "transient": ["transient"],
            "steadyThenTransient": ["steady", "transient"]}[cfg.RUN_MODE]


def write_system(c, cfg, d):
    st = stages(cfg)
    for stage in st:
        suffix = "" if len(st) == 1 else f".{stage}"
        c.write(f"system/controlDict{suffix}", control_dict(cfg, d, stage), obj="controlDict")
        c.write(f"system/fvSchemes{suffix}", fv_schemes(stage), obj="fvSchemes")
        c.write(f"system/fvSolution{suffix}", fv_solution(stage, d["all_flux"], is_wedge(cfg)), obj="fvSolution")
    if len(st) > 1:     # blockMesh etc. need a controlDict before the first stage copies one in
        for f in ("controlDict", "fvSchemes", "fvSolution"):
            shutil.copy(os.path.join(c.root, "system", f"{f}.steady"), os.path.join(c.root, "system", f))
    c.write("system/decomposeParDict", f"""
numberOfSubdomains  {cfg.N_PROCS};
method              scotch;
""")


